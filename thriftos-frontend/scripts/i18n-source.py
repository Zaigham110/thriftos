def nest(lang):
    out = {}
    for key, pair in T.items():
        node = out
        parts = key.split('.')
        for p in parts[:-1]:
            node = node.setdefault(p, {})
        node[parts[-1]] = pair[0 if lang == 'en' else 1]
    return out

